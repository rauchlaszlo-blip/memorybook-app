import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createHash,randomBytes,randomUUID} from 'node:crypto';
import {mkdir} from 'node:fs/promises';
import express from 'express';
import {Pool} from 'pg';
import {chromium,expect} from '@playwright/test';
import {localDatabaseUrl} from '../server/wedding/local-db';
import {migrateWedding} from '../server/wedding/migrate';
import {migratePilot} from '../server/pilot/auth';
import {createPilotApp} from '../server/pilot/app';
import {appTrialCookieName} from '../server/pilot/app-trial';
import {createWorkflowService,createExportWorker} from '../server/wedding/book-workflow';
import {arrange} from '../server/wedding/montage-layout';
import {defaultProfile,mockProvider} from '../shared/montage';
import type {Draft} from '../shared/montage';
import {seedMcpBook} from './fixtures/mcp-book';

test('app trial: fragment entry, real mobile collection/editor, save/approve/export, scoped navigation and explicit leave', {timeout:180000}, async()=>{
  const connectionString=localDatabaseUrl(),schema='app_trial_ui_'+randomUUID().replaceAll('-',''),admin=new Pool({connectionString});
  await admin.query(`CREATE SCHEMA ${schema}`);
  const pool=new Pool({connectionString,options:`-c search_path=${schema}`});
  const previousGrant=process.env.PILOT_APP_TRIAL_GRANT,previousView=process.env.PILOT_BOOK_VIEW_GRANT;
  let browser:Awaited<ReturnType<typeof chromium.launch>>|undefined,server:ReturnType<typeof express.application.listen>|undefined;
  const service=createWorkflowService(pool),worker=createExportWorker(pool,{pollMs:100});
  try{
    await migrateWedding(pool);await migratePilot(pool);
    const fixture=await seedMcpBook(pool),bookId=fixture.bookId,actor={ownerId:fixture.ownerId,kind:'owner' as const};
    const snapshot=await service.createSnapshot(actor,bookId,{key:randomUUID(),selectedIds:fixture.submissionIds});
    const initial:Draft={schema:1,format:'A4',spread:false,selected:fixture.submissionIds,excluded:[],profile:structuredClone(defaultProfile),pages:[{id:randomUUID(),background:'#fffaf4',locked:false,elements:[]}]};
    const arranged=await arrange(initial,snapshot.sources,mockProvider),first=await service.saveVersion(actor,bookId,{key:randomUUID(),parentId:null,snapshotId:snapshot.id,draft:arranged});
    // Open/package-backed book deliberately exercises both close and shop-link hiding.
    await pool.query('UPDATE event_books SET closed_at=NULL,package_version=1 WHERE id=$1',[bookId]);
    const key=randomBytes(32).toString('base64url'),expiresAt=new Date(Date.now()+3600000).toISOString();
    process.env.PILOT_APP_TRIAL_GRANT=JSON.stringify({bookId,ownerId:fixture.ownerId,expectedTitle:'Lili és Márk – fiktív MCP-próbakönyv',tokenHash:createHash('sha256').update(key).digest('hex'),authorizedAt:new Date(Date.now()-1000).toISOString(),expiresAt});
    delete process.env.PILOT_BOOK_VIEW_GRANT;
    const app=express();server=app.listen(0,'127.0.0.1');await new Promise<void>(resolve=>server!.once('listening',resolve));const address=server.address();assert.ok(address&&typeof address!=='string');
    const base='http://127.0.0.1:'+address.port;app.use(createPilotApp(pool,base));worker.start();
    browser=await chromium.launch({channel:'chrome'});
    const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,locale:'hu-HU'}),page=await context.newPage();page.setDefaultTimeout(20000);
    const errors:string[]=[],requests:{method:string;path:string}[]=[];let redeemCount=0,leakedFragment=false;
    page.on('pageerror',error=>errors.push(error.name));
    page.on('request',request=>{const url=new URL(request.url());if(request.url().includes(key)||url.search.includes('key='))leakedFragment=true;requests.push({method:request.method(),path:url.pathname});if(url.pathname==='/api/pilot/app-trial/redeem')redeemCount++;});
    page.on('dialog',dialog=>void dialog.accept());
    await page.goto(base+'/wedding/try#key='+key);
    await expect(page.getByRole('heading',{name:'Lili és Márk – fiktív MCP-próbakönyv',exact:true})).toBeVisible();
    await expect(page.getByRole('complementary',{name:'Próbamód',exact:true})).toContainText('Próbamód · fiktív emlékkönyv');
    await expect(page.locator('.trial-banner time')).toHaveAttribute('datetime',expiresAt);
    assert.equal(new URL(page.url()).hash,'');assert.equal(redeemCount,1);assert.equal(leakedFragment,false);
    const cookie=(await context.cookies()).find(item=>item.name===appTrialCookieName);assert.ok(cookie?.httpOnly&&cookie.secure);assert.equal(cookie.sameSite,'Strict');
    await expect(page.locator('input[type=password],a[href^="/pilot"],a[href^="/login"]')).toHaveCount(0);
    await expect(page.getByRole('button',{name:'Beküldés lezárása',exact:true})).toHaveCount(0);
    await expect(page.locator('.wedding-confirm')).toHaveCount(0);
    await expect(page.getByRole('region',{name:'Átnézendő tartalmak',exact:true})).toBeVisible();
    await expect(page.getByRole('heading',{name:'Fiktív vendég 3',exact:true})).toBeVisible();
    const guestLink=await page.getByLabel('Beküldési link',{exact:true}).inputValue();
    assert.equal(requests.filter(item=>item.method==='POST').length,1,'opening the collection only redeems access');
    await page.getByRole('link',{name:'Montázs, jóváhagyás és ellenőrző PDF',exact:true}).click();
    await expect(page.getByRole('link',{name:'Tervezet megnyitása és javítása',exact:true})).toBeVisible();
    await expect(page.getByRole('complementary',{name:'Próbamód',exact:true})).toBeVisible();
    await expect(page.getByText('ChatGPT-kapcsolat és hozzáférések',{exact:true})).toHaveCount(0);
    await page.getByRole('link',{name:'Tervezet megnyitása és javítása',exact:true}).click();
    await expect(page.getByRole('heading',{name:/fiktív MCP-próbakönyv – montázs/})).toBeVisible();
    await expect(page.locator('canvas.upper-canvas')).toBeVisible();
    await expect(page.getByRole('button',{name:'Új teljes mintatervezet',exact:true})).toHaveCount(0);
    await expect(page.getByText('ChatGPT-kapcsolat és hozzáférések',{exact:true})).toHaveCount(0);
    assert.equal(requests.filter(item=>item.path.startsWith('/api/mcp')).length,0);
    assert.equal((await service.getVersion(actor,bookId)).id,first.id,'navigation does not create a version');
    const photo=first.draft.pages[0].elements.find(item=>item.kind==='photo')!;
    await page.getByLabel('Szerkesztendő elem',{exact:true}).selectOption(photo.id);
    await page.getByLabel('Forgatás (fok)',{exact:true}).fill('4');await page.getByRole('heading',{name:'Kijelölt elem',exact:true}).click();
    await expect.poll(async()=>(await service.getVersion(actor,bookId)).draft.pages[0].elements.find(item=>item.id===photo.id)?.rotation).toBe(4);
    const edited=await service.getVersion(actor,bookId);assert.notEqual(edited.id,first.id);assert.equal(edited.approved_at,null);
    const approvalReply=page.waitForResponse(response=>response.url().endsWith('/approve')&&response.request().method()==='POST');
    await page.getByRole('button',{name:'Ezt a könyvváltozatot jóváhagyom',exact:true}).click();
    const approvalResponse=await approvalReply;assert.equal(approvalResponse.status(),200,await approvalResponse.text());
    await expect(page.getByRole('button',{name:'Jóváhagyott PDF készítése',exact:true})).toBeEnabled();
    await page.getByRole('button',{name:'Jóváhagyott PDF készítése',exact:true}).click();
    await expect(page.getByRole('link',{name:'Jóváhagyott ellenőrző PDF letöltése',exact:true})).toBeVisible({timeout:60000});
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true);
    await mkdir('test-results/app-trial',{recursive:true});await page.screenshot({path:'test-results/app-trial/local-mobile-editor.png',fullPage:true});
    await page.goto(guestLink);await expect(page.getByRole('complementary',{name:'Próbamód',exact:true})).toBeVisible();await expect(page.getByLabel('Neved',{exact:true})).toBeVisible();
    await page.getByRole('link',{name:'A próbakönyv áttekintése',exact:true}).click();await expect(page.getByRole('link',{name:/fiktív MCP-próbakönyv/})).toBeVisible();
    await expect(page.getByRole('button',{name:'Vendégkönyv létrehozása',exact:true})).toHaveCount(0);
    await expect(page.locator('a[href^="/pilot"],a[href^="/login"]')).toHaveCount(0);
    await page.getByRole('button',{name:'Kilépés a próbából',exact:true}).click();await expect(page.getByRole('complementary',{name:'Próbamód',exact:true})).toHaveCount(0);
    assert.equal((await context.cookies()).some(item=>item.name===appTrialCookieName),false);
    assert.equal((await context.request.get(base+'/api/wedding/books/'+bookId)).status(),401);
    assert.deepEqual(errors,[]);

    const invalid=await browser.newContext(),invalidPage=await invalid.newPage();let invalidPosts=0;
    invalidPage.on('request',request=>{if(request.method()==='POST')invalidPosts++;});
    await invalidPage.goto(base+'/wedding/try#key=invalid');await expect(invalidPage.getByRole('alert')).toContainText('nem érvényes');
    assert.equal(invalidPosts,0);assert.equal(new URL(invalidPage.url()).hash,'');await expect(invalidPage.getByRole('button',{name:'Kilépés a próbából',exact:true})).toBeVisible();
    await expect(invalidPage.locator('input[type=password]')).toHaveCount(0);
    await invalidPage.goto(base+'/wedding/try#key='+randomBytes(32).toString('base64url'));await expect(invalidPage.getByRole('alert')).toContainText('lejárt vagy nem érvényes');
    assert.equal(invalidPosts,1);await invalid.close();
  }finally{
    await browser?.close();await worker.stop();if(server){server.closeAllConnections();await new Promise<void>(resolve=>server!.close(()=>resolve()));}
    if(previousGrant===undefined)delete process.env.PILOT_APP_TRIAL_GRANT;else process.env.PILOT_APP_TRIAL_GRANT=previousGrant;
    if(previousView===undefined)delete process.env.PILOT_BOOK_VIEW_GRANT;else process.env.PILOT_BOOK_VIEW_GRANT=previousView;
    await pool.end();await admin.query(`DROP SCHEMA ${schema} CASCADE`);await admin.end();
  }
});
