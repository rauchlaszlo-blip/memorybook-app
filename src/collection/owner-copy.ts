export type OwnerCollectionKey=keyof typeof copy;
export function ownerCollectionText(language:AppLanguage,key:OwnerCollectionKey,values:Record<string,string|number>={}){
  let result:string=copy[key][language==='hu'?0:language==='en'?1:2];
  for(const [name,value] of Object.entries(values))result=result.replaceAll(`{${name}}`,String(value));
  return result;
}
